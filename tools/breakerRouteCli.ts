// Offline: derive an open guard route to an accessible source-labelled power room, without changing campus geometry.
import { writeFileSync } from 'node:fs';

import { GUARD_ROUTE } from '../src/config/guardRoute.ts';
import { pointInRoom } from '../src/world/roomIndex.ts';

import { auditFloor, loadCampusGeometry } from './navAudit.ts';

const geometry = loadCampusGeometry();
const room = geometry.rooms.find((entry) => entry.id === 'SVC-10')!;
const { grid, floor, solid } = auditFloor(geometry, { resolution: 0.1, radius: 0.36 });
const blocked = grid.inflate(
    solid.map((value) => (value ? 1 : 0)),
    0.36
);
const free = (k: number) => k >= 0 && k < floor.length && !!floor[k] && !blocked[k];
const start = grid.index(...GUARD_ROUTE[0]);
const goal = grid.index(-52, -12.1);
if (!free(start) || !free(goal) || !pointInRoom(grid.centre(goal), room)) throw new Error('Unsafe route endpoint');
const parent = new Int32Array(floor.length).fill(-1);
const queue = new Int32Array(floor.length);
let head = 0;
let tail = 1;
queue[0] = start;
parent[start] = start;
while (head < tail && parent[goal] < 0) {
    const k = queue[head++];
    for (const n of [k - 1, k + 1, k - grid.width, k + grid.width]) {
        if (!free(n) || parent[n] >= 0 || Math.abs((n % grid.width) - (k % grid.width)) > 1) continue;
        parent[n] = k;
        queue[tail++] = n;
    }
}
if (parent[goal] < 0) throw new Error('Power room unreachable');
const cells = [goal];
while (cells[cells.length - 1] !== start) cells.push(parent[cells[cells.length - 1]]);
cells.reverse();
const lineFree = (a: number, b: number) => {
    const [ax, az] = grid.centre(a),
        [bx, bz] = grid.centre(b);
    const steps = Math.ceil(Math.hypot(ax - bx, az - bz) / 0.025);
    for (let i = 0; i <= steps; i++)
        if (!free(grid.index(ax + ((bx - ax) * i) / steps, az + ((bz - az) * i) / steps))) return false;
    return true;
};
const route = [GUARD_ROUTE[0]];
let index = 0;
while (index < cells.length - 1) {
    let end = Math.min(cells.length - 1, index + 300);
    while (end > index + 1 && !lineFree(cells[index], cells[end])) end--;
    route.push(grid.centre(cells[end]).map((value) => Number(value.toFixed(2))) as [number, number]);
    index = end;
}
writeFileSync(
    new URL('../src/config/breakerRoute.ts', import.meta.url),
    `// GENERATED by tools/breakerRouteCli.ts. GAMEPLAY_AUTHORED route to source room SVC-10.\n// Sampled against floor, walls, glazing and colliding furniture at 0.36 m clearance; original geometry unchanged.\nexport const BREAKER_ROUTE: readonly [number, number][] = ${JSON.stringify(route)};\n`
);
console.log(JSON.stringify({ room: room.id, waypoints: route.length, destination: route.at(-1) }));
