// Derive compact, shared line-of-sight masks from the existing, publish-authorized campus collision layer.
// - src/config/executionOcclusion.ts: walls, glass, barriers and furniture block (arena seating excluded); used by the
//   back-execution gate in the browser and the Worker.
// - server/combatOcclusion.ts: only walls, glass and boundary barriers block (discs legitimately fly over furniture
//   and seats); used by the Worker to reject disc hits claimed through walls.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

import { auditFloor, CELL, loadCampusGeometry } from './navAudit.ts';

const geometry = loadCampusGeometry();
const source = new URL('../public/assets/campus/derived/world.json', import.meta.url);
const hash = createHash('sha256').update(readFileSync(source)).digest('hex');
const write = (
    target: string,
    name: string,
    note: string,
    pick: (solid: number, floor: number) => boolean,
    furniture: boolean
) => {
    const { grid, solid, floor } = auditFloor(geometry, { resolution: 0.1, furniture });
    const bits = new Uint8Array(Math.ceil(solid.length / 8));
    for (let i = 0; i < solid.length; i++) if (pick(solid[i], floor[i])) bits[i >> 3] |= 1 << (i & 7);
    writeFileSync(
        new URL(target, import.meta.url),
        `// GENERATED by tools/executionOcclusionCli.ts from existing FF01 colliders. GAMEPLAY_AUTHORED derivative.\n// world.json SHA-256: ${hash}. 0.1 m cells; ${note}.\nexport const ${name} = { x0: ${grid.x0}, z0: ${grid.z0}, width: ${grid.width}, height: ${grid.height}, resolution: ${grid.resolution}, bits: '${Buffer.from(bits).toString('base64')}' } as const;\n`
    );
    return { target, bytes: bits.length, cells: solid.length };
};
console.log(
    JSON.stringify({
        worldSha256: hash,
        masks: [
            write(
                '../src/config/executionOcclusion.ts',
                'EXECUTION_OCCLUSION',
                'wall/glass/barrier/furniture blocked, arena seating excluded',
                (solid, floor) => !floor || (!!solid && solid !== CELL.STAND),
                true
            ),
            write(
                '../server/combatOcclusion.ts',
                'COMBAT_OCCLUSION',
                'only walls, glazing and boundary barriers blocked (discs fly over furniture and seats)',
                (solid) => solid === CELL.WALL || solid === CELL.GLASS || solid === CELL.BARRIER,
                false
            )
        ]
    })
);
