// Derive a compact, shared line-of-sight mask from the existing, publish-authorized campus collision layer.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

import { auditFloor, CELL, loadCampusGeometry } from './navAudit.ts';

const { grid, solid, floor } = auditFloor(loadCampusGeometry(), { resolution: 0.1 });
const bits = new Uint8Array(Math.ceil(solid.length / 8));
for (let i = 0; i < solid.length; i++)
    if (!floor[i] || (solid[i] && solid[i] !== CELL.STAND)) bits[i >> 3] |= 1 << (i & 7);
const source = new URL('../public/assets/campus/derived/world.json', import.meta.url);
const hash = createHash('sha256').update(readFileSync(source)).digest('hex');
writeFileSync(
    new URL('../src/config/executionOcclusion.ts', import.meta.url),
    `// GENERATED by tools/executionOcclusionCli.ts from existing FF01 colliders. GAMEPLAY_AUTHORED derivative.\n// world.json SHA-256: ${hash}. 0.1 m cells; wall/glass/barrier/furniture blocked, arena seating excluded.\nexport const EXECUTION_OCCLUSION = {x0:${grid.x0},z0:${grid.z0},width:${grid.width},height:${grid.height},resolution:${grid.resolution},bits:'${Buffer.from(bits).toString('base64')}'} as const;\n`
);
console.log(JSON.stringify({ bytes: bits.length, cells: solid.length, worldSha256: hash }));
