// Derive server drop anchors from the source floor audit and the same authored arena colliders used in PlayCanvas.
import { writeFileSync, readFileSync } from 'node:fs';

import type { Triangle } from '../src/physics/boundaryBarriers.ts';
import { bowlCollider, standBlocks, standBlocksCollider, standStair, standStairCollider, tierRadiusAt } from '../src/world/arenaAccess.ts';
import { intersectRadius, ringRadii } from '../src/world/stadiumLayout.ts';

import { auditFloor, loadCampusGeometry } from './navAudit.ts';

const STEP = 0.35;
const RADIUS = 0.28;
const geometry = loadCampusGeometry();
const audit = auditFloor(geometry, { resolution: STEP, radius: RADIUS + 0.18 });
const anchors = new Map<string, [number, number, number]>();
const add = (x: number, y: number, z: number) => {
    const point: [number, number, number] = [Math.round(x * 100) / 100, Math.round(y * 100) / 100, Math.round(z * 100) / 100];
    anchors.set(`${Math.round(x / 0.7)},${Math.round(z / 0.7)},${Math.round(y / 0.2)}`, point);
};
for (let i = 0; i < audit.reached.length; i++) {
    if (audit.reached[i] && audit.floor[i] && !audit.inflated[i]) {
        const [x, z] = audit.grid.centre(i);
        add(x, 0.92, z);
    }
}
const world = JSON.parse(readFileSync(new URL('../public/assets/campus/derived/world.json', import.meta.url), 'utf8')) as { arena: { outline: [number, number][]; center: [number, number] } };
const { outline, center } = world.arena;
const radii = ringRadii(outline, center);
const meshes = [bowlCollider(radii, center)];
for (const [side, angle] of [['west', Math.PI], ['east', 0]] as const) {
    const wall = intersectRadius(outline, center, angle);
    const dir = side === 'west' ? -1 : 1;
    meshes.push(standBlocksCollider(standBlocks(side, center[0] + dir * wall)));
    meshes.push(standStairCollider(standStair(side, center, wall, tierRadiusAt(radii, angle, 0))));
}
const tris: Triangle[] = [];
for (const name of ['Arena_Court', 'Arena_StandBase']) tris.push(...geometry.scene.triangles(name));
for (const mesh of meshes) for (let i = 0; i < mesh.indices.length; i += 3) {
    const p = (index: number): [number, number, number] => { const o = mesh.indices[index] * 3; return [mesh.positions[o], mesh.positions[o + 1], mesh.positions[o + 2]]; };
    tris.push([p(i), p(i + 1), p(i + 2)]);
}
const cell = 0.35;
const buckets = new Map<string, number[]>();
const bucketKey = (x: number, z: number) => `${Math.floor(x / cell)},${Math.floor(z / cell)}`;
for (let i = 0; i < tris.length; i++) {
    const t = tris[i];
    const nx = (t[1][2] - t[0][2]) * (t[2][1] - t[0][1]) - (t[1][1] - t[0][1]) * (t[2][2] - t[0][2]);
    const ny = (t[1][2] - t[0][2]) * (t[2][0] - t[0][0]) - (t[1][0] - t[0][0]) * (t[2][2] - t[0][2]);
    const nz = (t[1][1] - t[0][1]) * (t[2][0] - t[0][0]) - (t[1][0] - t[0][0]) * (t[2][1] - t[0][1]);
    const length = Math.hypot(nx, ny, nz);
    if (length < 1e-7 || Math.abs(ny / length) < 0.65) continue;
    const x0 = Math.min(...t.map(p => p[0])), x1 = Math.max(...t.map(p => p[0]));
    const z0 = Math.min(...t.map(p => p[2])), z1 = Math.max(...t.map(p => p[2]));
    for (let x = x0; x <= x1; x += cell) for (let z = z0; z <= z1; z += cell) {
        const key = bucketKey(x, z); const list = buckets.get(key) ?? []; list.push(i); buckets.set(key, list);
    }
}
const heightAt = (x: number, z: number): number | null => {
    let best = -Infinity;
    for (const i of buckets.get(bucketKey(x, z)) ?? []) {
        const [[ax, ay, az], [bx, by, bz], [cx, cy, cz]] = tris[i];
        const d = (bz - cz) * (ax - cx) + (cx - bx) * (az - cz);
        if (Math.abs(d) < 1e-8) continue;
        const a = ((bz - cz) * (x - cx) + (cx - bx) * (z - cz)) / d;
        const b = ((cz - az) * (x - cx) + (ax - cx) * (z - cz)) / d;
        const c = 1 - a - b;
        if (a < -1e-4 || b < -1e-4 || c < -1e-4) continue;
        best = Math.max(best, a * ay + b * by + c * cy);
    }
    return Number.isFinite(best) ? best : null;
};
for (let x = -75; x <= 75; x += cell) for (let z = -75; z <= 75; z += cell) {
    const y = heightAt(x, z);
    if (y === null || y < 0.25) continue;
    let supported = true;
    for (let i = 0; i < 8; i++) {
        const a = i * Math.PI / 4;
        const next = heightAt(x + Math.cos(a) * RADIUS * 0.78, z + Math.sin(a) * RADIUS * 0.78);
        if (next === null || Math.abs(next - y) > 0.17) { supported = false; break; }
    }
    if (supported) add(x, y + 0.92, z);
}
const values = [...anchors.values()].sort((a, b) => a[1] - b[1] || a[0] - b[0] || a[2] - b[2]);
if (!values.some(([, y]) => y > 4)) throw new Error('No elevated walkable collision surfaces were derived');
writeFileSync(new URL('../src/config/goldDropSurfaces.ts', import.meta.url), `// GENERATED by tools/goldDropSurfacesCli.ts from the immutable FF-01 GLB and runtime arena collider definitions.\n// Base anchors passed source-derived reachability and capsule-clearance audit; elevated anchors have continuous support\n// across the capsule footprint on upward faces of the actual runtime stand/stair/bowl colliders.\n// Campus geometry status remains SOURCE_DERIVED_3D_UNVERIFIED.\nexport const GOLD_DROP_SURFACES: readonly (readonly [number, number, number])[] = ${JSON.stringify(values)};\n`);
console.log(`generated ${values.length} drop anchors; ${values.filter(([, y]) => y > 1.2).length} elevated`);
