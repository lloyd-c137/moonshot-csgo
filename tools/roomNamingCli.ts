// Regenerates src/config/roomNaming.ts from the 2026-08-06 room source and FF-01 (see tools/roomNaming.ts).
import { writeFileSync } from 'node:fs';

import { deriveRoomNaming } from './roomNaming.ts';

const naming = deriveRoomNaming();
writeFileSync(
    new URL('../src/config/roomNaming.ts', import.meta.url),
    `// GENERATED by tools/roomNamingCli.ts (npm run derive:rooms). Do not edit by hand.\n// Room names and division from the owner's 2026-08-06 drawing model mapped onto FF-01 regions (owner decision 2026-10-17).\nexport const ROOM_NAMING = ${JSON.stringify(naming)} as const;\n`
);
console.log(
    JSON.stringify({
        rooms: naming.rooms.length,
        fitted: naming.rooms.filter((room) => room.polygon).map((room) => room.id),
        kept: naming.kept.length,
        unnumbered: naming.unnumbered,
        retired: naming.retired,
        fit: naming.fit
    })
);
