// Derives GAMEPLAY_AUTHORED respawn points for the shared world: reachable corridor floor (outside room
// polygons and the arena), at least 1.2 m from any wall, glazing or furniture, spread by farthest-point sampling.
// Writes src/config/spawns.ts. Run: node tools/spawnPointsCli.ts
import { writeFileSync } from 'node:fs';

import { SAFE_SPAWN } from '../src/config/gameplay.ts';
import { findRoomAt } from '../src/world/roomIndex.ts';

import { auditFloor, loadCampusGeometry } from './navAudit.ts';

const COUNT = 24;
const geometry = loadCampusGeometry();
const audit = auditFloor(geometry);
const clearance = audit.grid.inflate(audit.solid.map((v) => (v ? 1 : 0)) as Uint8Array, 1.2);
const rooms = geometry.rooms.filter((room) => room.hasRegion);
const candidates: [number, number][] = [];
for (let k = 0; k < audit.reached.length; k += 7) {
    if (!audit.reached[k] || !audit.floor[k] || clearance[k]) continue;
    const [x, z] = audit.grid.centre(k);
    if (findRoomAt([x, z], rooms)) continue;
    candidates.push([x, z]);
}
const chosen: [number, number][] = [[SAFE_SPAWN.x, SAFE_SPAWN.z]];
while (chosen.length < COUNT) {
    let best = candidates[0];
    let bestDistance = -1;
    for (const c of candidates) {
        const d = Math.min(...chosen.map(([x, z]) => Math.hypot(c[0] - x, c[1] - z)));
        if (d > bestDistance) {
            bestDistance = d;
            best = c;
        }
    }
    chosen.push(best);
}
const round = (v: number) => Math.round(v * 100) / 100;
writeFileSync(
    new URL('../src/config/spawns.ts', import.meta.url),
    `// GENERATED by tools/spawnPointsCli.ts — GAMEPLAY_AUTHORED respawn points (capsule centre X/Z) on reachable corridor
// floor, ≥1.2 m from walls, glazing and furniture. The first is the east-entry safe spawn. Shared with the server.
export const SPAWN_POINTS: readonly [number, number][] = ${JSON.stringify(chosen.map(([x, z]) => [round(x), round(z)]))};
`
);
console.log(candidates.length, 'candidates;', chosen.length, 'spawns');
